-- Create core schemas
CREATE DATABASE IF NOT EXISTS RISK_COPILOT_DB;
CREATE SCHEMA IF NOT EXISTS RISK_COPILOT_DB.COMPLIANCE_CORE;
USE SCHEMA RISK_COPILOT_DB.COMPLIANCE_CORE;

-- 1. Create Identity Access Master Table
CREATE OR REPLACE TABLE IDENTITY_ACCESS_MASTER (
    USER_ID INT IDENTITY(1,1),
    USERNAME VARCHAR(50) UNIQUE NOT NULL,
    DISPLAY_NAME VARCHAR(100),
    ACCESS_ROLE VARCHAR(50),
    CLEARANCE_LEVEL VARCHAR(30),
    PASSWORD VARCHAR(50), -- Matching text-based lookup configurations
    DEPARTMENT VARCHAR(50),
    IS_ACTIVE BOOLEAN DEFAULT TRUE,
    LAST_LOGIN TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP()
);

